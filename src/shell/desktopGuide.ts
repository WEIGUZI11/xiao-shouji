export interface DesktopGuideSection {
  id: string;
  title: string;
  summary: string;
  intro?: string;
  items: string[];
  ordered?: boolean;
}

export function getDesktopGuideView(sections: DesktopGuideSection[], activeSectionId: string | null) {
  const activeSection = sections.find((section) => section.id === activeSectionId) || null;
  return {
    mode: activeSection ? 'detail' : 'directory',
    activeSection,
    sections,
  } as const;
}

